#!/usr/bin/env python3
"""Writes frontend/public/legal/attributions/third-party.txt: the npm and Python packages Loam ships or
runs on, with versions and licenses.

npm: the production packages in frontend/package-lock.json (its `license` field).
Python: the runtime packages named in requirements.txt (test-only packages skipped) and everything they
depend on, from the installed metadata of the interpreter that runs this script (use the project's venv).

    .venv/bin/python scripts/gen_third_party_licenses.py
"""
import json
import os
import re
import sys
from importlib import metadata

from packaging.requirements import Requirement

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "frontend", "public", "legal", "attributions", "third-party.txt")
TEST_ONLY = {"pytest", "pytest-asyncio"}


def npm_packages():
    with open(os.path.join(ROOT, "frontend", "package-lock.json")) as f:
        pkgs = json.load(f)["packages"]
    out = {}
    for path, p in pkgs.items():
        if not path or p.get("dev") or p.get("optional") and not p.get("license"):
            continue
        name = path.split("node_modules/")[-1]
        out[(name, p.get("version", "?"))] = p.get("license") or "UNKNOWN"
    return sorted(out.items())


def _norm(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def _license(dist):
    md = dist.metadata
    expr = md.get("License-Expression")
    if expr:
        return expr
    lic = (md.get("License") or "").strip()
    first = lic.splitlines()[0].strip() if lic else ""  # some packages put the whole license text here
    if first and len(first) < 60:
        return first
    classes = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    return ", ".join(classes) or "UNKNOWN"


def python_packages():
    with open(os.path.join(ROOT, "requirements.txt")) as f:
        roots = [_norm(re.split(r"[<>=!~ ;\[]", line.strip())[0]) for line in f if line.strip() and not line.startswith("#")]
    seen, todo = {}, [r for r in roots if r not in TEST_ONLY]
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            seen[name] = ("not installed here", "UNKNOWN")
            continue
        seen[name] = (dist.version, _license(dist))
        for req in dist.requires or []:
            r = Requirement(req)
            if r.marker is not None and not r.marker.evaluate({"extra": ""}):
                continue  # an extra, or a dependency for another Python version or platform
            todo.append(_norm(r.name))
    return sorted(seen.items())


def main():
    lines = [
        "Third-party software used by Loam",
        "",
        "Generated by scripts/gen_third_party_licenses.py. Licenses are as declared in each package's own",
        "metadata; a package's full license text ships with the package.",
        "",
        "== Web app (npm, production dependencies) ==",
    ]
    lines += [f"{name} {ver}  {lic}" for (name, ver), lic in npm_packages()]
    lines += ["", "== Server (Python) =="]
    lines += [f"{name} {ver}  {lic}" for name, (ver, lic) in python_packages()]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(lines)} lines)")


if __name__ == "__main__":
    sys.exit(main())
